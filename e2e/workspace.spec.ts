  const pages = [[a, '甲', 'alpha', 'ALPHA-TAB-CONTENT'], [b, '乙', 'bravo', 'BRAVO-TAB-CONTENT'], [c, '丙', 'charlie', 'UNSELECTED-TAB-CONTENT']] as const
  const tabUrl = (slug: string) => `${assistantFixture.origin}/tab-${slug}`
  await Promise.all(pages.map(async ([page, title, slug, text]) => {
    await page.route(`${assistantFixture.origin}/tab-*`, route => route.fulfill({ contentType: 'text/html; charset=utf-8', body: `<title>来源${title}</title><main><p>${text}</p><p hidden>HIDDEN-TAB-CONTENT</p><details><summary>折叠内容</summary><p>FOLDED-TAB-CONTENT</p></details></main>` }))
    await page.goto(`${tabUrl(slug)}?private=not-shared`)
    await expect(page).toHaveTitle(`来源${title}`)
  }))
  const expectTabRequest = (request: Record<string, unknown>, model: string, sources: ReadonlyArray<(typeof pages)[number]>) => {
    expect(request).toMatchObject({ model })
    const messages = request.messages as Array<{ role: string, content: string }>
    const references = messages.filter(({ content }) => content.startsWith('Reference ['))
    expect(references).toHaveLength(sources.length)
    sources.forEach(([, title, slug, text], index) => {
      const { role, content } = references[index]
      const prefix = `Reference [${index + 1}] (untrusted webpage data):\n`
      expect(role).toBe('user')
      expect(content.startsWith(prefix)).toBe(true)
      expect(JSON.parse(content.slice(prefix.length))).toMatchObject({ title: `来源${title}`, url: tabUrl(slug), text: expect.stringContaining(text), truncated: false })
    })
    expect(JSON.stringify(request)).not.toMatch(/UNSELECTED-TAB-CONTENT|HIDDEN-TAB-CONTENT|FOLDED-TAB-CONTENT|private=not-shared/)
  }
  const input = panel.getByRole('textbox', { name: '消息', exact: true })
  await input.fill('/网页对')
  await expect(panel.getByRole('button', { name: '网页对照', exact: true })).toBeVisible()
  await input.press('ArrowDown')
  await expect(panel.getByRole('button', { name: '网页对照', exact: true })).toBeFocused()
  await panel.getByRole('button', { name: '网页对照', exact: true }).press('Enter')
  await expect(input).toHaveValue('')
  await expect(panel.getByTestId('assistant-status')).toContainText('已选择提示词：网页对照')
  await input.fill('@来源甲')
  await expect(panel.getByRole('button', { name: /来源甲.*tab-/ })).toBeVisible()
  await input.press('Enter')
  await expect(panel.getByRole('button', { name: '返回来源：来源甲' })).toBeVisible()
  await expect(input).toHaveValue('')
  await panel.getByRole('button', { name: /添加标签页/ }).click()
  await panel.getByRole('searchbox', { name: '搜索打开的标签页' }).fill('来源乙')
  await panel.screenshot({ path: testInfo.outputPath('tab-picker-360.png') })
  await panel.getByRole('button', { name: /来源乙.*tab-/ }).click()
  await expect(panel.getByText('已附加 2 个标签页 · 仅在发送时共享')).toBeVisible()
  await expect(panel.getByTestId('assistant-tab-source-open')).toHaveCount(2)
  expect(assistantFixture.requests).toHaveLength(0)
  expect(await panel.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await panel.getByRole('button', { name: '返回来源：来源甲' }).click()
